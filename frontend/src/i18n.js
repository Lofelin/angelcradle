export function translateKey(key, lang) {
  if (lang === 'en' || !keyDict[lang]) return key
  const dict = keyDict[lang]
  // Try exact match first, then with underscores replaced
  return dict[key] || dict[key.replace(/_/g, ' ')] || key
}

